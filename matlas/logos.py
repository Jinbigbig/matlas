def crest_url(name: str) -> str:
    """队名 → 队徽站点相对路径（assets/logo/teams/{id}.png）。

    不拼域名：页面分布在 /、/days/、/matches/ 不同深度，绝对地址在本地
    预览必 404；相对路径由渲染层按页深补 ../ 前缀，本地与线上同构。
    无映射时返回空串（调用方退化为首字占位圆）。
    """
    tid = TEAM_CREST.get((name or "").strip())
    if not tid:
        return ""
    return f"assets/logo/teams/{tid}.png"


def apply(days) -> int:
    """给缺 logo 的球队补上队徽相对路径。已有值不覆盖（数据侧可显式指定）。"""
    n = 0
    for d in days:
        for m in d.matches:
            for t in (m.home, m.away):
                if getattr(t, "logo", ""):
                    continue
                u = crest_url(t.name)
                if u:
                    t.logo = u
                    n += 1
    return n
