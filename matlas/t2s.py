def _opencc():
    """懒加载 opencc，只在第一次调用时试；缺失后不再重试。"""
    global _cc, _cc_tried
    if _cc is not None or _cc_tried:
        return _cc
    _cc_tried = True
    try:
        from opencc import OpenCC

        _cc = OpenCC("t2s")
    except Exception:
        _cc = None
    return _cc


def to_simplified(text: str) -> str:
    """繁体归一；输入为空或已是简体时原样返回。"""
    if not text:
        return text
    cc = _opencc()
    if cc is not None:
        try:
            return cc.convert(text)
        except Exception:
            pass
    return text.translate(_FALLBACK_TABLE)
